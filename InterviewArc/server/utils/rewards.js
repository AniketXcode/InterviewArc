export const normalizeRewardInventory = (inventory = {}) => ({
  ...getDefaultInventory(),
  ...inventory,
  rolePacks: Array.isArray(inventory?.rolePacks) ? inventory.rolePacks : [],
  companyPacks: Array.isArray(inventory?.companyPacks) ? inventory.companyPacks : [],
  merchClaims: Array.isArray(inventory?.merchClaims) ? inventory.merchClaims : [],
  themes: Array.isArray(inventory?.themes) ? inventory.themes : [],
  consumables: {
    ...getDefaultInventory().consumables,
    ...(inventory?.consumables || {}),
  },
});

const getCatalogItemState = ({ item, inventory, user }) => {
  let owned = false;
  let balance = 0;

  if (item.inventoryKey) {
    owned = Boolean(inventory[item.inventoryKey]);
  }

  if (item.inventoryCollection && item.inventoryValue) {
    owned = inventory[item.inventoryCollection]?.includes(item.inventoryValue);
  }

  if (item.balanceKey) {
    balance = inventory.consumables?.[item.balanceKey] || 0;
  }

  const subscriptionActive =
    item.productType === "subscription" &&
    user?.subscription?.tier === "PRO" &&
    user?.subscription?.expiresAt &&
    new Date(user.subscription.expiresAt) > new Date();

  return {
    owned: owned || subscriptionActive,
    balance,
    affordable: (user?.coins || 0) >= item.coinCost,
  };
};

export const buildStoreCatalogForUser = (user) => {
  const inventory = normalizeRewardInventory(user?.rewardInventory);

  return STORE_CATALOG.map((item) => {
    const state = getCatalogItemState({ item, inventory, user });

    return {
      ...item,
      ...state,
    };
  });
};

