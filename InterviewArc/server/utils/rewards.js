export const isPhysicalReward = (item) => item?.category === "Merch Rewards";

export const awardBadges = ({ completedInterviews = 0, currentStreak = 0, finalScore = 0, mode = "Technical" }) => {
  const earnedKeys = [];

  if (completedInterviews === 0) earnedKeys.push("first-interview");
  if (finalScore >= 8) earnedKeys.push("score-starter");
  if (mode === "Technical" && finalScore >= 8) earnedKeys.push("technical-ace");
  if (mode === "HR" && finalScore >= 8) earnedKeys.push("hr-master");
  if (currentStreak >= 5) earnedKeys.push("streak-5");

  return earnedKeys.map((key) => ({
    ...BADGE_DEFINITIONS[key],
    earnedAt: new Date(),
  }));
};

export const calculateInterviewRewards = ({
  finalScore = 0,
  currentStreak = 0,
  completedInterviews = 0,
  mode = "Technical",
  currentXp = 0,
}) => {
  const baseCoins = 24 + Math.round(finalScore * 4);
  const streakBonus = Math.min(currentStreak, 7) * 3;
  const performanceBonus = finalScore >= 8 ? 18 : finalScore >= 6 ? 8 : 0;
  const xpEarned = 45 + Math.round(finalScore * 12);
  const coinsEarned = baseCoins + streakBonus + performanceBonus;
  const updatedXp = currentXp + xpEarned;
  const previousLevel = getLevelFromXp(currentXp);
  const newLevel = getLevelFromXp(updatedXp);

  return {
    coinsEarned,
    xpEarned,
    streakBonus,
    performanceBonus,
    newLevel,
    leveledUp: newLevel > previousLevel,
    badges: awardBadges({
      completedInterviews,
      currentStreak,
      finalScore,
      mode,
    }),
  };
};

export const buildRewardsOverview = ({ user, completedInterviews = 0, highestScore = 0 }) => {
  const level = getLevelFromXp(user?.xp || 0);
  const xpForNextLevel = getXpForNextLevel(level);
  const inventory = normalizeRewardInventory(user?.rewardInventory);
  const now = new Date();
  const subscriptionIsActive =
    user?.subscription?.tier === "PRO" &&
    user?.subscription?.expiresAt &&
    new Date(user.subscription.expiresAt) > now;

  return {
    coins: user?.coins || 0,
    xp: user?.xp || 0,
    level,
    xpForNextLevel,
    currentStreak: user?.streak?.current || 0,
    completedInterviews,
    highestScore,
    badges: user?.badges || [],
    inventory,
    subscription: {
      tier: subscriptionIsActive ? "PRO" : user?.subscription?.tier || "FREE",
      expiresAt: user?.subscription?.expiresAt || null,
      isActive: Boolean(subscriptionIsActive),
    },
    recentPurchases: (user?.storeHistory || []).slice(-6).reverse(),
    challenges: getInterviewChallengeProgress({
      completedInterviews,
      highestScore,
      currentStreak: user?.streak?.current || 0,
    }),
  };
};

const appendStoreHistory = (user, item) => {
  user.storeHistory = Array.isArray(user.storeHistory) ? user.storeHistory : [];
  user.storeHistory.push({
    itemId: item.id,
    title: item.title,
    category: item.category,
    coinCost: item.coinCost,
    productType: item.productType,
    purchasedAt: new Date(),
  });
};

const addDays = (date, days) => {
  const nextDate = new Date(date);
  nextDate.setDate(nextDate.getDate() + days);
  return nextDate;
};

export const applyStorePurchase = ({ user, itemId }) => {
  const catalogItem = STORE_CATALOG.find((item) => item.id === itemId);

  if (!catalogItem) {
    return { error: "Store item not found." };
  }

  user.rewardInventory = normalizeRewardInventory(user.rewardInventory);
  user.storeHistory = Array.isArray(user.storeHistory) ? user.storeHistory : [];

  if ((user.coins || 0) < catalogItem.coinCost) {
    return { error: "Not enough coins for this purchase." };
  }

  if (catalogItem.productType === "unlock") {
    if (catalogItem.inventoryKey && user.rewardInventory[catalogItem.inventoryKey]) {
      return { error: "You already own this unlock." };
    }

    if (
      catalogItem.inventoryCollection &&
      catalogItem.inventoryValue &&
      user.rewardInventory[catalogItem.inventoryCollection]?.includes(catalogItem.inventoryValue)
    ) {
      return { error: "You already unlocked this product." };
    }
  }

  user.coins -= catalogItem.coinCost;

  if (catalogItem.inventoryKey) {
    user.rewardInventory[catalogItem.inventoryKey] = true;
  }

  if (catalogItem.inventoryCollection && catalogItem.inventoryValue) {
    user.rewardInventory[catalogItem.inventoryCollection].push(catalogItem.inventoryValue);
  }

  if (catalogItem.balanceKey) {
    user.rewardInventory.consumables[catalogItem.balanceKey] =
      (user.rewardInventory.consumables[catalogItem.balanceKey] || 0) + (catalogItem.quantity || 1);
  }

  if (catalogItem.productType === "subscription") {
    const now = new Date();
    const baseDate =
      user.subscription?.expiresAt && new Date(user.subscription.expiresAt) > now
        ? new Date(user.subscription.expiresAt)
        : now;

    user.subscription = {
      ...user.subscription,
      tier: "PRO",
      expiresAt: addDays(baseDate, catalogItem.durationDays || 0),
    };
  }

  appendStoreHistory(user, catalogItem);

  return { item: catalogItem };
};
